static int TestDecode(const unsigned char *stream, size_t len,
  gdcm::PhotometricInterpretation::PIType pitype, bool expectRGB)
{
  const gdcm::PhotometricInterpretation pi( pitype );
  gdcm::Image image;
  image.SetNumberOfDimensions( 2 );
  image.SetDimension( 0, 16 );
  image.SetDimension( 1, 8 );
  gdcm::PixelFormat pf( gdcm::PixelFormat::UINT8 );
  pf.SetSamplesPerPixel( 3 );
  image.SetPixelFormat( pf );
  image.SetPhotometricInterpretation( pi );
  image.SetTransferSyntax( gdcm::TransferSyntax::JPEG2000 );

  gdcm::SmartPointer<gdcm::SequenceOfFragments> sq = new gdcm::SequenceOfFragments;
  gdcm::Fragment frag;
  frag.SetByteValue( (const char*)stream, (uint32_t)len );
  sq->AddFragment( frag );
  gdcm::DataElement pixeldata( gdcm::Tag(0x7fe0,0x0010) );
  pixeldata.SetValue( *sq );
  image.SetDataElement( pixeldata );

  std::vector<char> buffer( image.GetBufferLength() );
  if( !image.GetBuffer( buffer.data() ) )
    {
    std::cerr << "GetBuffer failed for: " << pi << std::endl;
    return 1;
    }
  if( expectRGB )
    {
    const unsigned char *p = (const unsigned char*)buffer.data();
    if( p[0] < 200 || p[1] > 50 || p[2] > 50 )
      {
      std::cerr << "Pixel is not red for: " << pi << " : "
        << (int)p[0] << "," << (int)p[1] << "," << (int)p[2] << std::endl;
      return 1;
      }
    }
  const gdcm::PhotometricInterpretation expected = expectRGB ?
    gdcm::PhotometricInterpretation( gdcm::PhotometricInterpretation::RGB ) : pi;
  if( image.GetPhotometricInterpretation() != expected )
    {
    std::cerr << "Reported " << image.GetPhotometricInterpretation()
      << " instead of " << expected << " for: " << pi << std::endl;
    return 1;
    }
  return 0;
}

static int TestDecode422(gdcm::PhotometricInterpretation::PIType pitype)
{
  return TestDecode( j2k422, sizeof(j2k422), pitype, true );
}

int TestJPEG2000Codec1(int, char *[])
{
  int r = 0;
  r += TestDecode422( gdcm::PhotometricInterpretation::YBR_FULL_422 );
  r += TestDecode422( gdcm::PhotometricInterpretation::YBR_FULL );
  r += TestDecode422( gdcm::PhotometricInterpretation::YBR_ICT );
  r += TestDecode422( gdcm::PhotometricInterpretation::RGB );
  // Not subsampled: no chroma conversion, the label is left alone.
  r += TestDecode( j2k444, sizeof(j2k444),
    gdcm::PhotometricInterpretation::YBR_ICT, false );
  return r;
}
